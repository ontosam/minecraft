const dismiss = async () => { for (let k = 0; k < 10; k++) { if (!(await celOpen())) return; await p.sleep(450); await tapSel('#cel-ok', 300); } };
const cell = (i) => J(`__mine.cellCenter(${i})`);
const openIdx = () => J(`[...Array(${N}).keys()].filter(i => __mine.game.isOpen(i))`);
const setBoard = (arr) => E(`(() => { const g = __mine.game; const o = [...Array(${N}).keys()].filter(i => g.isOpen(i)); g.s.board = Array(${N}).fill(null); ${JSON.stringify(arr)}.forEach((c, k) => { if (k < o.length) g.s.board[o[k]] = c; }); __mine.renderBoard(); })()`);
const noError = () => E(`getComputedStyle(document.getElementById('error-overlay')).display === 'none'`);
const S = () => J(`__mine.game.s`);
const tut = () => E(`__mine.tut()`);
const typeCard = async (num) => { for (const d of num) { const k = await J(`(() => { const b = [...document.querySelectorAll('#co-pad button')].find(b => b.textContent === '${d}'); const r = b.getBoundingClientRect(); return {x: r.left + r.width/2, y: r.top + r.height/2}; })()`); await p.tap(k.x, k.y, 15); } };
const key = async (k, code, vk) => { await p.send('Input.dispatchKeyEvent', { type: 'keyDown', key: k, code, windowsVirtualKeyCode: vk }); await p.send('Input.dispatchKeyEvent', { type: 'keyUp', key: k, code, windowsVirtualKeyCode: vk }); };

